"""Reproducible2x building-art overrides from frozen resolved pre-change snapshots.
Icons, construction stages, global status FX, gameplay footprints and assets stay intact.
China's new shared Soviet shipyard deliberately retains the Soviet native size.
"""
from pathlib import Path
import json,re,sys
ROOT=Path(__file__).resolve().parents[2]
sys.path.insert(0,str(ROOT/'tools'))
from test_soviet_building_art import traits
P=ROOT/'art-source/china-scrin-scale2x'
actors=json.loads((P/'actors-before.json').read_text());images=json.loads((P/'sequences-before.json').read_text())
scaled={};seq=['# Generated by tools/art/prepare_china_scrin_scale.py; explicit2x per resolved body state.']
for image,text in images.items():
 if image=='syrd.allies':continue
 fields=traits(text);defaults=fields.get('Defaults','');dm=re.search(r'\n\tScale: ([^\n]+)',defaults);ds=float(dm[1]) if dm else 1
 states={}
 for name,value in fields.items():
  if name in ('Defaults','construction','make') or name.startswith(('icon','bib','emp-','chrono-','mind-')):continue
  m=re.search(r'\n\tScale: ([^\n]+)',value);old=float(m[1]) if m else ds
  states[name]=old*2
 if states:
  scaled[image]=states;seq += ['',image+':']
  for name,scale in states.items():seq += [f'\t{name}:',f'\t\tScale: {scale:g}']
(ROOT/'mods/ca/sequences/china-scrin-building-scale.yaml').write_text('\n'.join(seq)+'\n')
actual={n.lower():n for faction in ('china','scrin') for n in re.findall(r'^([\w.]+):',(ROOT/f'mods/ca/rules/{faction}/structures.yaml').read_text(),re.M)}
bibs={'chcommand':4,'chpower':2,'chbarracks':2,'chsupply':3,'chweap':4,'chpropaganda':3,'chinternetcenter':3,'chairport':4,'chgatling':1,'chbunker':2,'chpropagandatower':1,'chsilo':3}
rules=['# China/Scrin visual-only2x sizing; original production/footprints/weapon definitions retained.']
for name,text in actors.items():
 if name in ('spen','syrd'):continue
 a=traits(text);changes=[]
 if name=='chsyrd':
  changes=['\tRenderSprites:','\t\tImage: spen.soviet','\tIsometricSelectable:']
  for key in ('DecorationBounds','DecorationHeight'):
   v=re.search(r'\n\t'+key+r': ([^\n]+)',traits(actors['spen'])['IsometricSelectable'])[1]
   changes.append(f'\t\t{key}: {v}')
 else:
  if name in bibs:
   if 'WithBuildingBib' in a:changes.append('\t-WithBuildingBib:')
   changes += ['\tWithIdleOverlay@CHINABIB:',f'\t\tImage: sovietbib{bibs[name]}x{bibs[name]}','\t\tSequence: idle','\t\tRequiresCondition: !build-incomplete','\t\tIsDecoration: true']
  # Preserve trait/weapon behavior; only attachment vectors track enlarged sprites.
  for trait,value in a.items():
   keys=[]
   if trait.startswith('Turreted'):keys=['Offset']
   elif trait.startswith('Armament'):keys=['LocalOffset']
   if keys:
    for key in keys:
     m=re.search(r'\n\t'+key+r': ([^\n]+)',value)
     if m:
      numbers=[int(n.strip())*2 for n in m[1].split(',')]
      changes += [f'\t{trait}:',f'\t\t{key}: '+','.join(map(str,numbers))]
  if 'IsometricSelectable' in a:
   selection=[]
   for key in ('Bounds','DecorationBounds','Height','DecorationHeight'):
    m=re.search(r'\n\t'+key+r': ([^\n]+)',a['IsometricSelectable'])
    if m:
     numbers=[int(n.strip())*2 for n in m[1].split(',')]
     selection.append(f'\t\t{key}: '+', '.join(map(str,numbers)))
   if selection:changes+=['\tIsometricSelectable:']+selection
 if changes:rules+=['',actual[name]+':']+changes
(ROOT/'mods/ca/rules/china-scrin-building-art.yaml').write_text('\n'.join(rules)+'\n')
(P/'binding.json').write_text(json.dumps({'scales':scaled,'china_bibs':bibs,'shared_yard':'spen.soviet','yard_scale_unchanged':True,'gameplay_footprints_unchanged':True},indent=2)+'\n')
print('China/Scrin2x sequence scales and China Soviet bibs generated; shared Soviet shipyard keeps native size.')
