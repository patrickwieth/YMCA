"""Source-qualified cannon portraits only: no combat stats or compatibility changes."""
import json
import math
import re
from pathlib import Path
from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parents[2]
ART = ROOT / 'mods/ca/bits/modular/cannons'
MANIFEST = Path(__file__).with_name('cannon-art-bindings.json')
BEGIN = '# BEGIN GENERATED MODULAR CANNON ART'
END = '# END GENERATED MODULAR CANNON ART'


def bindings():
    return json.loads(MANIFEST.read_text(encoding='utf-8'))


def key(name):
    return 'cannon-' + Path(name).stem.replace(' ', '-')


def assets():
    names = sorted({b['image'] for b in bindings()['bindings'] if b['image']})
    rows = math.ceil(len(names) * 2 / 4)
    height = 1 << (max(1, rows * 256) - 1).bit_length()
    sheet = Image.new('RGBA', (1024, height))
    regions = []
    for i, name in enumerate(names):
        with Image.open(ART / name) as image:
            if image.mode != 'RGBA' or max(image.size) > 256:
                raise ValueError(f'Expected RGBA cannon fitting a 256px tile: {name}')
            for rotation in range(2):
                sprite = image if not rotation else image.transpose(Image.Transpose.ROTATE_270)
                slot = i * 2 + rotation
                x, y = slot % 4 * 256, slot // 4 * 256
                sheet.paste(sprite, (x, y))
                regions.append((key(name) + ('-rotated' if rotation else ''), x, y, *sprite.size))
    chrome = '\n'.join([BEGIN, 'modular-cannon-icons:', '\tImage: ca|bits/modular/cannon-icons.png', '\tRegions:'] +
                       [f'\t\t{k}: {x}, {y}, {w}, {h}' for k, x, y, w, h in regions] + [END])
    return sheet, chrome


def cs_source():
    lines = ['// Generated by tools/modular/generate_cannon_art.py. Presentation only.',
             'namespace OpenRA.Mods.CA.Modular', '{',
             '\tpublic sealed record CustomVehicleCannonArt(string Sprite, int Barrels, string Label, string SourceActor, string SourceWeapon)',
             '\t{', '\t\tpublic static CustomVehicleCannonArt For(string hull, string weapon) => (hull, weapon) switch', '\t\t{']
    q = lambda text: json.dumps(text, ensure_ascii=False)
    for b in bindings()['bindings']:
        sprite = q(key(b['image'])) if b['image'] else 'null'
        lines.append(f'\t\t\t({q(b["hull"])}, {q(b["weapon"])}) => new({sprite}, {b["barrels"]}, {q(b["label"])}, {q(b["actor"])}, {q(b["native_weapon"])}),')
    return '\n'.join(lines + ['\t\t\t_ => null', '\t\t};', '\t}', '}', ''])


def review_sheet():
    names = sorted(p.name for p in ART.glob('*.png'))
    used = {b['image'] for b in bindings()['bindings'] if b['image']}
    sheet = Image.new('RGBA', (4 * 300, math.ceil(len(names) / 4) * 112), '#171f25')
    draw = ImageDraw.Draw(sheet)
    for i, name in enumerate(names):
        x, y = i % 4 * 300, i // 4 * 112
        with Image.open(ART / name) as image:
            sheet.alpha_composite(image, (x + (300 - image.width) // 2, y + 30))
        draw.text((x + 8, y + 6), name, fill='#dae1cf')
        draw.text((x + 8, y + 94), 'BOUND TO STOCK' if name in used else 'RESERVE',
                  fill='#7acc91' if name in used else '#b3b3b3')
    return sheet


if __name__ == '__main__':
    sheet, chrome = assets()
    sheet.save(ROOT / 'mods/ca/bits/modular/cannon-icons.png')
    path = ROOT / 'mods/ca/chrome.yaml'
    text = path.read_text(encoding='utf-8')
    if BEGIN not in text or END not in text:
        raise ValueError('Missing generated cannon chrome markers')
    text = re.sub(re.escape(BEGIN) + r'.*?' + re.escape(END), lambda _: chrome, text, flags=re.S)
    path.write_text(text, encoding='utf-8')
    (ROOT / 'OpenRA.Mods.CA/Modular/CustomVehicleCannonArt.cs').write_text(cs_source(), encoding='utf-8')
    review_sheet().save(ROOT / 'docs/modular/cannon-art-review.png')
    print(f'Generated cannon atlas {sheet.size}, chrome regions, bindings and review sheet.')
