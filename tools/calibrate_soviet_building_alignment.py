import argparse,json,re,copy
from calibrate_gdi_building_alignment import ROOT,propose,report,signed_round,world_offset
GROUND_CONTACTS={
 'fact.soviet':[(41,198),(362,177)],
 'powr.soviet':[(6,190),(176,161)],
 'apwr.soviet':[(10,175),(432,189)],
 'tpwr':[(7,183),(248,183)],
 'dome.soviet':[(42,118),(13,167),(244,117)],
 'stek':[(6,128),(176,130)],
 'barr':[(12,88),(5,135),(250,117)],
 'weap.soviet':[(22,143),(382,171)],
 'fix.soviet':[(5,346),(304,302)],
 'afld':[(5,64),(209,50),(218,141)],
 'spen':[(47,132),(393,152)],
 'iron':[(11,180),(235,180)],
 'mslo':[(83,193),(376,215)], # Fully-open doors; registration covers all seven frames.
 'indp':[(18,192),(243,207)],
 'soviet_refinery':[(9,186),(243,185)],
 'nkorea_bunker':[(12,99),(224,103),(227,144)],
 'cloning_vats':[(17,185),(238,200)],
 'tsla':[(7,171),(132,171)],
}
ACTOR_NAMES={n.lower():n for n in ['FACT.Soviet','POWR.Soviet','APWR.Soviet','TPWR','DOME.Soviet','STEK','BARR',
 'WEAP.Soviet','FIX.Soviet','AFLD','SPEN','IRON','MSLO','INDP','Soviet_Refinery','NKOREA_BUNKER','Cloning_Vats','TSLA']}

def propose_soviet(entry):
 extra=[f'bits/soviet/buildings/missile silo {i}.png' for i in range(1,7)] if entry['Actor']=='mslo' else []
 if entry['Actor']!='tsla':return propose(entry,GROUND_CONTACTS,'sovietbib',extra)
 # Tesla's unchanged coil silhouette is wider than its 1x1 ground base. Keep
 # the art-enclosing UI box independent of the actual bib (not a collision box).
 envelope=copy.deepcopy(entry)
 for bib in envelope['Bibs']:
  if bib['Image'].startswith('sovietbib'):bib['Image']='sovietbib2x2'
 result=propose(envelope,GROUND_CONTACTS,'sovietbib')
 w,h=result['SourceSize'];contacts=GROUND_CONTACTS['tsla']
 ox=signed_round(w/2-sum(x for x,y in contacts)/len(contacts))
 oy=signed_round(h-w/4-sum(y for x,y in contacts)/len(contacts))
 dx,dy=ox-result['Offset'][0],oy-result['Offset'][1]
 tx,ty=entry['TileSize'];scale=entry['TileScale']
 result['DecorationBounds'][2]=world_offset(signed_round(result['DecorationBounds'][2]*tx/scale)+dx,tx,scale)
 result['DecorationBounds'][3]=world_offset(signed_round(result['DecorationBounds'][3]*ty/scale)+dy,ty,scale)
 result['Offset']=[ox,oy];result['GroundRearY']+=dy
 result['Bib']='sovietbib1x1';result['BibCells']=[1,1]
 result['SelectionMayOverhangBib']=True
 result['GroundContactPolicy']='Center native ground contacts on 1x1 bib; tolerate 2px raster edge overhang. Coil/UI envelope stays wider.'
 return result

def emit(values):
 # Complete generated override files. Existing definitions, including missile
 # animation frames and filename exceptions, remain untouched.
 source=(ROOT/'mods/ca/sequences/soviet-building-art.yaml').read_text()
 blocks={b.split(':',1)[0]:b for b in re.split(r'(?m)(?=^[^\s#][^\n]*:)',source) if ':' in b}
 rules=['# Generated by tools/calibrate_soviet_building_alignment.py --emit. Decoration only.']
 sequences=['# Generated by tools/calibrate_soviet_building_alignment.py --emit. Native PNG offsets only.']
 for e in values:
  rules.append(f"{ACTOR_NAMES[e['Actor']]}:\n\tIsometricSelectable:\n\t\tDecorationBounds: {', '.join(map(str,e['DecorationBounds']))}\n\t\tDecorationHeight: {e['DecorationHeight']}")
  states=re.findall(r'^\t([^\t:]+):$',blocks[e['Image']],re.M)
  assert states,e['Image']
  sequences.append(e['Image']+':\n'+'\n'.join(f"\t{s}:\n\t\tOffset: {','.join(map(str,e['Offset']))}" for s in states))
 (ROOT/'mods/ca/rules/soviet/building-alignment.yaml').write_text('\n\n'.join(rules)+'\n')
 (ROOT/'mods/ca/sequences/soviet-building-placement.yaml').write_text('\n\n'.join(sequences)+'\n')

if __name__=='__main__':
 p=argparse.ArgumentParser(description=__doc__);p.add_argument('geometry',type=Path)
 p.add_argument('--propose',type=Path);p.add_argument('--preview',type=Path);p.add_argument('--emit',action='store_true');a=p.parse_args()
 entries=json.loads(a.geometry.read_text(encoding='utf-8-sig'))
 if a.propose or a.emit:
  values=[propose_soviet(e) for e in entries if e['Actor'] in GROUND_CONTACTS]
  if a.emit:emit(values)
  if a.propose:a.propose.write_text(json.dumps({'policy':'Reviewed native ground contacts; Tesla centered on 1x1 bib with a wider visual selection envelope. Other original bib registrations retained. Scale 1; no PNG edits.', 'entries':values},indent=2)+'\n')
  for e in values:print(e['Actor'],e['Offset'],e['DecorationBounds'],e['DecorationHeight'])
 if a.preview:report(entries,a.preview,GROUND_CONTACTS,'sovietbib')
